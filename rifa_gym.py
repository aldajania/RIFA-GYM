async def main():
    print("Initializing RIFA Gym...")
    kb = KnowledgeBase(DOCUMENTS)
    agent = RifaGymAgent(kb, ConversationMemory())

    # Subscription plans
    print("\n--- Subscription Plans & Projected Revenue ---")
    per_plan, total = estimate_plan_revenue(subscription_plans)
    for name, rev in per_plan.items():
        d = subscription_plans[name]
        print(f"{name} ({d['duration']}): {d['price']} SAR | Est. annual revenue: {rev:,.2f} SAR")
    print(f"Total projected revenue: {total:,.2f} SAR")

    # Booking validation
    print("\n--- Booking Validation ---")
    for data in (
        {"member_name": "Sara", "member_age": 26, "member_gender": "Female",
         "zone": "Pilates", "subscription_tier": "Monthly Basic"},
        {"member_name": "Sam", "member_age": 12, "member_gender": "Male",
         "zone": "Cardio", "subscription_tier": "Weekly Pass"},
    ):
        try:
            print("Valid booking:", GymBooking(**data).model_dump())
        except ValidationError as e:
            print(f"Invalid booking: {e.errors()[0]['loc'][0]} - {e.errors()[0]['msg']}")

    # Agent
    print("\n--- Agent: Retrieval ---")
    query = "What equipment is available for free squats and what is our financial outlook?"
    result = agent.process_request(query)
    print(f"Query tokens: {result['query_tokens']}")
    print("Dense results:")
    for doc_id, doc in result["dense"]:
        print(f"  [{doc_id}] {doc}")
    print("TF-IDF results:")
    for doc_id, doc in result["lexical"]:
        print(f"  [{doc_id}] {doc}")
    print(f"Messages in memory window: {len(result['history'])}")

    # Financials
    fin_table, t_rev, t_exp, n_prof, roi = agent.finance
    print("\n--- Financial Metrics ---")
    print(f"Total annual revenue : {t_rev:,.2f} SAR")
    print(f"Total annual expenses: {t_exp:,.2f} SAR")
    print(f"Net annual profit    : {n_prof:,.2f} SAR")
    print(f"Annual ROI           : {roi:.2f}%")

    # Clustering & evaluation
    print("\n--- Clustering ---")
    for doc, label in zip(DOCUMENTS, kb.clusters):
        print(f"  cluster {label}: {doc.split(':')[0]}")

    print("\n--- Retrieval Evaluation ---")
    print("(TF-IDF returns only chunks with a nonzero match, so it can return fewer than k;")
    print(" Dense always returns k. Compare P@1 for a like-for-like precision.)")
    results = {}
    for k in EVAL_KS:
        for name, fn in (("Dense", kb.search_dense), ("TF-IDF", kb.search_tfidf)):
            results[(name, k)] = evaluate_search(fn, k=k)
            print(f"  {name:<7}" + ", ".join(f"{m} {v:.2f}" for m, v in results[(name, k)].items()))

    # Async tools
    print("\n--- Async Tool Execution ---")
    availability, zones = await asyncio.gather(
        run_tool("check_gym_zone_availability", "Pilates", "Monthly Basic"),
        run_tool("list_gym_zones"),
    )
    print(f"Availability: {availability}")
    print(f"Zones: {zones}")

    # Workout plan
    print("\n--- Workout Plan ---")
    print(generate_ai_workout_plan(age=26, gender="Female", preferred_zone="Weightlifting"))

    # Dashboard
    build_dashboard(fin_table, results[("Dense", DASHBOARD_K)], results[("TF-IDF", DASHBOARD_K)], DASHBOARD_PATH)
    print(f"\nDashboard saved to {DASHBOARD_PATH}")
    show_image(DASHBOARD_PATH)


