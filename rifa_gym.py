def estimate_plan_revenue(plans: dict) -> tuple[dict, float]:
    per_plan = {}
    for name, d in plans.items():
        if "Weekly" in name:
            per_plan[name] = d["price"] * 52 * (d["subscribers"] * WEEKLY_RENEWAL_RATIO)
        elif "Monthly" in name:
            per_plan[name] = d["price"] * 12 * d["subscribers"]
        else:
            per_plan[name] = d["price"] * d["subscribers"]
    return per_plan, sum(per_plan.values())


def calculate_annual_financials(
    monthly_revenue=25000, monthly_expenses=15000, growth_rate=0.05, initial_investment=150000.0
):
    revenues, expenses, net_profits = [], [], []
    curr_rev = monthly_revenue
    for _ in range(12):
        revenues.append(curr_rev)
        expenses.append(monthly_expenses)
        net_profits.append(curr_rev - monthly_expenses)
        curr_rev *= 1 + growth_rate / 12

    net_prof = sum(net_profits)
    roi = net_prof / initial_investment * 100
    table = pd.DataFrame({
        "Month": [f"Month {m}" for m in range(1, 13)],
        "Revenue": [round(r, 2) for r in revenues],
        "Expenses": [round(e, 2) for e in expenses],
        "Net Profit": [round(p, 2) for p in net_profits],
    })
    return table, sum(revenues), sum(expenses), net_prof, roi


