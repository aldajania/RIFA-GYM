class KnowledgeBase:
    def __init__(self, documents: list[str], n_clusters: int = 3):
        self.documents = documents
        self.ids = [f"chunk_{i}" for i in range(len(documents))]

        # Lexical index
        self.tfidf = TfidfVectorizer(stop_words="english")
        self.tfidf_matrix = self.tfidf.fit_transform([preprocess(d) for d in documents])

        # Dense index
        self.embedder = SentenceTransformer("all-MiniLM-L6-v2")
        embeddings = self.embedder.encode(documents)
        client = chromadb.Client()
        self.collection = client.get_or_create_collection(
            "rifa_gym_knowledge", metadata={"hnsw:space": "cosine"}
        )
        self.collection.upsert(
            ids=self.ids, documents=documents, embeddings=embeddings.tolist()
        )

        # Topic clusters (on embeddings, which capture meaning better than
        # word counts for short documents)
        self.clusters = KMeans(n_clusters=n_clusters, random_state=42, n_init=10).fit_predict(
            embeddings
        )

    def search_dense(self, query: str, top_k: int = 2) -> list[tuple[str, str]]:
        q_vec = self.embedder.encode([query]).tolist()
        res = self.collection.query(query_embeddings=q_vec, n_results=top_k)
        return list(zip(res["ids"][0], res["documents"][0]))

    def search_tfidf(self, query: str, top_k: int = 2) -> list[tuple[str, str]]:
        q_vec = self.tfidf.transform([preprocess(query)])
        sims = cosine_similarity(q_vec, self.tfidf_matrix).flatten()
        order = sims.argsort()[::-1][:top_k]
        return [(self.ids[i], self.documents[i]) for i in order if sims[i] > 0]


