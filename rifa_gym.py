def metric_names(k: int) -> list[str]:
    return [f"Precision@{k}", f"Recall@{k}", f"F1@{k}", f"HitRate@{k}", f"MRR@{k}"]


def evaluate_retrieval(retrieved_ids, relevant_ids, k=3):
    retrieved = list(retrieved_ids)[:k]
    relevant = set(relevant_ids)

    tp = len(set(retrieved) & relevant)
    precision = tp / len(retrieved) if retrieved else 0.0
    recall = tp / len(relevant) if relevant else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
    hit_rate = 1.0 if tp > 0 else 0.0

    mrr = 0.0
    for rank, doc_id in enumerate(retrieved, start=1):
        if doc_id in relevant:
            mrr = 1.0 / rank
            break
    return precision, recall, f1, hit_rate, mrr


def evaluate_search(search_fn, eval_set=EVAL_SET, k=3) -> dict:
    rows = [
        evaluate_retrieval([doc_id for doc_id, _ in search_fn(q, k)], rel, k)
        for q, rel in eval_set
    ]
    return dict(zip(metric_names(k), np.mean(rows, axis=0)))


