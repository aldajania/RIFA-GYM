class ConversationMemory:
    """SQLite-backed chat history with a sliding window on reads."""

    def __init__(self, path: str = DB_PATH, window: int = MEMORY_WINDOW):
        self.path = path
        self.window = window
        with sqlite3.connect(self.path) as conn:
            conn.execute(
                """CREATE TABLE IF NOT EXISTS chat_history (
                       id INTEGER PRIMARY KEY AUTOINCREMENT,
                       member_query TEXT NOT NULL,
                       assistant_response TEXT NOT NULL,
                       created_at TEXT DEFAULT CURRENT_TIMESTAMP)"""
            )

    def save(self, query: str, response: str) -> None:
        with sqlite3.connect(self.path) as conn:
            conn.execute(
                "INSERT INTO chat_history (member_query, assistant_response) VALUES (?, ?)",
                (query, response),
            )

    def load_recent(self) -> list[tuple[str, str]]:
        # rowid exists on every SQLite table, so this also works with
        # databases created by older versions of this script.
        with sqlite3.connect(self.path) as conn:
            rows = conn.execute(
                "SELECT member_query, assistant_response FROM chat_history "
                "ORDER BY rowid DESC LIMIT ?",
                (self.window,),
            ).fetchall()
        return rows[::-1]  # oldest first


def generate_ai_workout_plan(age: int, gender: str, preferred_zone: str) -> str:
    zone = preferred_zone.lower()
    if zone == "pilates":
        plan = "3x Reformer Pilates weekly focusing on core strength, flexibility, and posture correction."
    elif zone == "weightlifting":
        plan = "4x Upper/Lower split weightlifting sessions focusing on free squats and progressive overload."
    else:
        plan = "5x High-Intensity Cardio (Treadmill intervals & HIIT bikes) for stamina and fat burning."
    if age > 35:
        plan += " [Note: Extended warm-up and joint mobility protection included]."
    return plan


class RifaGymAgent:
    def __init__(self, kb: KnowledgeBase, memory: ConversationMemory, name="RIFA-Master-Agent"):
        self.name = name
        self.kb = kb
        self.memory = memory
        self.finance = calculate_annual_financials()  # computed once

    def process_request(self, query: str) -> dict:
        dense = self.kb.search_dense(query, top_k=2)
        lexical = self.kb.search_tfidf(query, top_k=2)
        self.memory.save(query, f"Context: {dense[0][1][:60]}...")
        return {
            "query_tokens": count_tokens(query),
            "dense": dense,
            "lexical": lexical,
            "history": self.memory.load_recent(),
        }


